from abc import abstractmethod

from tool_calling_data_generation.data_generators.models.canonical_format import CanonicalSample


class BaseConverter:
    """
    Base class for converters. The key objective is that we are able to convert a vendor-specific format (for example Qwen2.5) to a canonical format when vLLM or any prediction model creates this, so we have a common format when we upload to HF. The converter must also support the other direction - from canonical format to vendor-specific format - so that we can convert back to the original format for training.

    The canonical format is defined in CanonicalFormat class. It includes the following fields:
    - system_prompt: The system prompt that is given to the model.
    - user_prompt: The user prompt that is given to the model.
    - tools: A list of tools that are available to the model.
    - chosen: The tool calls that are chosen by the model. Used for DPO.
    - rejected: The tool calls that are rejected by the model. Used for DPO.
    - completion: The final completion generated by the model. Used for SFT.

    This class is abstract - the original implementations needs to be made elsewhere.
    """

    def __init__(self, model_id: str = None):
        self.model_id: str = model_id
        pass

    @abstractmethod
    def to_canonical_format(self, vendor_specific_format) -> CanonicalSample:
        """
        Converts a vendor-specific format to the canonical format.
        """
        pass

    @abstractmethod
    def from_canonical_format(self, canonical_format: CanonicalSample) -> dict:
        """
        Converts a canonical format to the vendor-specific format.
        """
        pass
